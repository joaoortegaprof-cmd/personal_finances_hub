def icon(name: str, color: str = "#FFFFFF", size: int = 20) -> QIcon:
    """
    Retorna um QIcon renderizado a partir de um SVG inline.

    Args:
        name:  Nome do ícone (chave em _SVGS). Ícone desconhecido → "add".
        color: Cor CSS (hex, rgb, nome). Substitui "currentColor" no SVG.
        size:  Tamanho em pixels (quadrado).

    Returns:
        QIcon pronto para uso em QPushButton, QToolButton, QAction, etc.
    """
    svg_str = _SVGS.get(name, _SVGS["add"])
    svg_str = svg_str.replace("currentColor", color)

    renderer = QSvgRenderer(QByteArray(svg_str.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter)
    painter.end()

    return QIcon(pixmap)


def category_icon(category: str, color: str = "#8B90A7", size: int = 16) -> QIcon:
    """
    Retorna o ícone correspondente à categoria de uma transação.

    Args:
        category: Valor da categoria (ex: "moradia", "HOUSING").
        color:    Cor do ícone (padrão: cinza neutro).
        size:     Tamanho em pixels.
    """
    icon_name = CATEGORY_ICON_MAP.get(category, "cat_other")
    return icon(icon_name, color=color, size=size)
